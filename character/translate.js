window.gefu_char = function (name, label, doOpen) {
	if (!name) return "";
	if (doOpen) {
		if (typeof lib === "undefined" || !lib.character[name]) return;
		if (typeof ui === "undefined" || !ui.click || typeof ui.click.charactercard !== "function") return;
		ui.click.charactercard(name, null, null, true, null, name);
		return;
	}
	const text = label || (typeof get !== "undefined" && get.translation ? get.translation(name) : name);
	const safe = String(name).replace(/"/g, '\\"');
	return `<a class='gefu_text' onclick='window.gefu_char("${safe}","",1)'><font color='#FF69B4'><u>${text}</u></font></a>`;
};
window.gefu_card = function (name, label, doOpen, el) {
	if (!name) return "";
	if (doOpen) {
		if (typeof game === "undefined" || typeof ui === "undefined") return;
		if (typeof game.closePoptipDialog === "function") game.closePoptipDialog();
		let dialog = null;
		try {
			dialog = ui.create.dialog("hidden", "notouchscroll");
			dialog.addSmall([[name], "vcard"]);
			const node = dialog.buttons && dialog.buttons[0];
			if (node && typeof get.nodeintro === "function") get.nodeintro(node, null, null, dialog);
			dialog.classList.add("popped", "static");
			dialog.style.zIndex = "100";
			ui.window.appendChild(dialog);
			let pos = null;
			try {
				if (el && typeof el.getBoundingClientRect === "function") {
					const rect = el.getBoundingClientRect();
					pos = { clientX: rect.left + rect.width / 2, clientY: rect.bottom };
				}
			} catch (e) { }
			if (!pos) {
				try {
					const ev = window.event;
					if (ev && typeof ev.clientX == "number") pos = ev;
				} catch (e) { }
			}
			if (typeof lib !== "undefined" && typeof lib.placePoppedDialog === "function") {
				lib.placePoppedDialog(dialog, pos || { clientX: ui.window.offsetWidth / 2, clientY: ui.window.offsetHeight / 2 });
			}
		} catch (e) {
			if (dialog) {
				try { dialog.remove(); } catch (e2) { }
			}
			dialog = null;
		}
		if (dialog) {
			const layer = ui.create.div(".poplayer", ui.window);
			layer.style.zIndex = "99";
			const closeTip = function () {
				layer.remove();
				dialog.delete();
			};
			layer.listen(closeTip);
			dialog.listen(closeTip);
			return;
		}
		try {
			const card = game.createCard2(name);
			if (card) {
				ui.create.dialog([card]).open();
				return;
			}
		} catch (e) { }
		if (typeof window.gefu_text === "function") {
			const info = get.translation(name + "_info");
			window.gefu_text(get.translation(name) + (info ? "<br><br>" + info : ""));
		}
		return;
	}
	const text = label || (typeof get !== "undefined" && get.translation ? get.translation(name) : name);
	const safe = String(name).replace(/"/g, '\\"');
	return `<a class='gefu_text' onclick='window.gefu_card("${safe}","",1,this)'><font color='#FF0000'><u>【${text}】</u></font></a>`;
};
